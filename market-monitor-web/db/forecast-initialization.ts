/** Cloudflare-independent DDL used by runtime initialization and SQLite tests. */
export function forecastInitializationStatements() {
  return [
    `CREATE TABLE IF NOT EXISTS forecasts (
      id INTEGER PRIMARY KEY AUTOINCREMENT,
      profile_id INTEGER NOT NULL,
      symbol TEXT NOT NULL,
      direction TEXT NOT NULL CHECK (direction IN ('bullish', 'bearish', 'neutral')),
      confidence INTEGER NOT NULL CHECK (confidence BETWEEN 0 AND 100),
      thesis TEXT NOT NULL,
      supporting_evidence TEXT NOT NULL,
      counter_evidence TEXT NOT NULL,
      setup_tag TEXT NOT NULL,
      evaluation_date TEXT NOT NULL,
      target_kind TEXT NOT NULL,
      target_price REAL,
      target_lower REAL,
      target_upper REAL,
      invalidation_price REAL CHECK (invalidation_price IS NULL OR invalidation_price > 0),
      analysis_seed_json TEXT,
      analysis_seed_scenario_id TEXT,
      status TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'active', 'target_hit', 'invalidated', 'expired', 'cancelled')),
      activated_at TEXT,
      market_data_as_of TEXT,
      activation_price REAL,
      activation_currency TEXT,
      market_provider TEXT,
      resolved_at TEXT,
      resolution_reason TEXT,
      created_at TEXT NOT NULL,
      updated_at TEXT NOT NULL,
      CHECK (
        (target_kind = 'price' AND target_price IS NOT NULL AND target_price > 0 AND target_lower IS NULL AND target_upper IS NULL)
        OR
        (target_kind = 'range' AND target_price IS NULL AND target_lower IS NOT NULL AND target_lower > 0 AND target_upper IS NOT NULL AND target_upper > target_lower)
      ),
      CHECK ((analysis_seed_json IS NULL AND analysis_seed_scenario_id IS NULL) OR (analysis_seed_json IS NOT NULL AND analysis_seed_scenario_id IS NOT NULL)),
      FOREIGN KEY (profile_id) REFERENCES investment_profiles(id) ON DELETE CASCADE
    )`,
    'CREATE INDEX IF NOT EXISTS idx_forecasts_profile_status ON forecasts(profile_id, status, updated_at)',
    'CREATE INDEX IF NOT EXISTS idx_forecasts_profile_symbol ON forecasts(profile_id, symbol, updated_at)',
    `CREATE TABLE IF NOT EXISTS forecast_events (
      id INTEGER PRIMARY KEY AUTOINCREMENT,
      forecast_id INTEGER NOT NULL,
      profile_id INTEGER NOT NULL,
      revision INTEGER NOT NULL CHECK (revision > 0),
      event_type TEXT NOT NULL CHECK (event_type IN ('draft_created', 'draft_updated', 'activated', 'cancelled', 'amendment', 'review_note')),
      note TEXT NOT NULL DEFAULT '',
      payload_json TEXT NOT NULL,
      created_at TEXT NOT NULL,
      FOREIGN KEY (forecast_id) REFERENCES forecasts(id) ON DELETE CASCADE,
      FOREIGN KEY (profile_id) REFERENCES investment_profiles(id) ON DELETE CASCADE
    )`,
    'CREATE UNIQUE INDEX IF NOT EXISTS idx_forecast_events_revision ON forecast_events(forecast_id, revision)',
    'CREATE INDEX IF NOT EXISTS idx_forecast_events_profile_forecast ON forecast_events(profile_id, forecast_id, created_at)',
    `CREATE TABLE IF NOT EXISTS analysis_snapshots (
      id INTEGER PRIMARY KEY AUTOINCREMENT,
      forecast_id INTEGER NOT NULL,
      profile_id INTEGER NOT NULL,
      symbol TEXT NOT NULL,
      generated_at TEXT NOT NULL,
      analysis_as_of TEXT NOT NULL,
      completed_bar_as_of TEXT,
      provider TEXT NOT NULL,
      adjustment_mode TEXT NOT NULL,
      engine_version TEXT NOT NULL,
      ruleset_version TEXT NOT NULL,
      data_hash TEXT NOT NULL,
      scenario_id TEXT NOT NULL,
      setup TEXT NOT NULL,
      timeframe TEXT NOT NULL,
      lifecycle_state TEXT NOT NULL,
      direction TEXT NOT NULL CHECK (direction IN ('bullish', 'bearish', 'undetermined')),
      range_lower REAL NOT NULL,
      range_upper REAL NOT NULL,
      range_height REAL NOT NULL,
      measured_target REAL,
      evidence_json TEXT NOT NULL,
      warnings_json TEXT NOT NULL,
      report_json TEXT NOT NULL,
      created_at TEXT NOT NULL,
      CHECK (range_lower > 0 AND range_upper > range_lower AND range_height > 0),
      FOREIGN KEY (forecast_id) REFERENCES forecasts(id) ON DELETE CASCADE,
      FOREIGN KEY (profile_id) REFERENCES investment_profiles(id) ON DELETE CASCADE
    )`,
    'CREATE UNIQUE INDEX IF NOT EXISTS idx_analysis_snapshots_forecast ON analysis_snapshots(forecast_id)',
    'CREATE INDEX IF NOT EXISTS idx_analysis_snapshots_profile_symbol ON analysis_snapshots(profile_id, symbol, created_at)',
  ] as const;
}
